        let transform=CGAffineTransform(a:scale,b:0,c:0,d:scale,tx:rect.midX-box.midX*scale,ty:rect.midY-box.midY*scale)
        return (provider == .claude ? OriginalProviderPaths.claude : OriginalProviderPaths.openai).applying(transform)
    }
}

public struct ProviderLogo: View {
    public let provider: Provider
    @Environment(\.colorScheme) private var scheme
    @Environment(\.widgetRenderingMode) private var mode
    public init(_ provider:Provider) {self.provider=provider}
    public var body:some View {
        ProviderMark(provider:provider)
            .fill(mode != .fullColor ? Color.primary : provider == .claude ? Color(hex:0xD97757) : QuotaPalette.text(scheme))
            .aspectRatio(1,contentMode:.fit)
            .accessibilityHidden(true)
    }
}
